"""Embed the curated collection so index.html works offline as well as on a server."""
import json
from pathlib import Path
from urllib.parse import urlparse

root = Path(__file__).resolve().parent
items = json.loads((root / 'prompts.json').read_text(encoding='utf-8'))
assert isinstance(items, list)
ids = set()
for item in items:
    assert all(isinstance(item.get(k), str) and item[k].strip() for k in ('id', 'title', 'category', 'prompt'))
    assert item['id'] not in ids, 'Duplicate prompt id'
    ids.add(item['id'])
    assert item.get('kind', 'prompt') in ('prompt', 'skill', 'website')
    if item.get('kind') in ('skill', 'website'):
        assert isinstance(item.get('description'), str) and item['description'].strip(), 'Skill/website requires a brief purpose'
    if item.get('kind') == 'website':
        url = urlparse(item.get('source', ''))
        assert url.scheme in ('http', 'https') and url.netloc, 'Website requires a valid address'
    for field in ('officialUrl', 'repository', 'documentation'):
        if item.get(field):
            link = urlparse(item[field])
            assert link.scheme in ('http', 'https') and link.netloc, f'Invalid {field}'
    for preview in (item.get('preview'), item.get('cardPreview')):
        if not preview:
            continue
        assert preview['type'] in ('image', 'animation', 'video')
        path = (root / preview['src']).resolve()
        assert path.is_relative_to((root / 'assets').resolve()) and path.is_file()
data = json.dumps(items, ensure_ascii=False).replace('<', r'\u003c').replace('>', r'\u003e').replace('&', r'\u0026')
template = (root / 'index.template.html').read_text(encoding='utf-8')
assert template.count('__PROMPTS__') == 1
(root / 'index.html').write_text(template.replace('__PROMPTS__', data), encoding='utf-8')
print(f'Built index.html with {len(items)} prompts.')

# Cloud likes only accept ids listed in public.content_items. The sync-content-ids workflow applies this file on
# every push to main; it can also be run by hand in the Supabase SQL editor.
assert len(items) >= 20, 'Refusing to generate a content sync from an almost empty prompts.json'
sql_ids = ["'" + item['id'].replace("'", "''") + "'" for item in items]
id_list = ', '.join(sql_ids)
(root / 'supabase' / 'sync-content.sql').write_text(
    '-- Generated by build.py: mirrors prompts.json ids into public.content_items. Safe to re-run.\n'
    '-- New ids are added, removed ids are only marked inactive (likes are kept), returning ids are reactivated.\n'
    'begin;\n'
    '-- Guard: abort if this would deactivate more than 10 items and over 20% of the active ones, unless the\n'
    "-- session set shiju.allow_mass_deactivate = 'on' first.\n"
    'do $guard$\ndeclare dropping int; active_now int;\nbegin\n'
    f'  select count(*) into dropping from public.content_items where active and id not in ({id_list});\n'
    '  select count(*) into active_now from public.content_items where active;\n'
    "  if dropping > 10 and dropping * 5 > active_now and coalesce(current_setting('shiju.allow_mass_deactivate', true), '') <> 'on' then\n"
    "    raise exception 'Refusing to deactivate % of % active content items; set shiju.allow_mass_deactivate = on to confirm.', dropping, active_now;\n"
    '  end if;\nend\n$guard$;\n'
    'insert into public.content_items (id) values\n' + ',\n'.join(f'({i})' for i in sql_ids) + '\n'
    'on conflict (id) do update set active = true, updated_at = now() where not public.content_items.active;\n'
    'update public.content_items set active = false, updated_at = now()\n'
    f'where active and id not in ({id_list});\n'
    'commit;\n', encoding='utf-8', newline='\n')
print(f'Wrote supabase/sync-content.sql with {len(items)} content ids.')
